let currentLanguage = localStorage.getItem("echoFourLanguage") || "en";
let data = {};

const messagesEl = document.getElementById("messages");
const inputEl = document.getElementById("input");
const formStartedAtEl = document.getElementById("formStartedAt");

function t(key) {
  return translations[currentLanguage][key] || translations.en[key] || key;
}

function translateValue(value) {
  if (!value) return value;
  return valueTranslations[currentLanguage]?.[value] || value;
}

function applyLanguage() {
  document.documentElement.lang = currentLanguage;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });

  document.querySelectorAll("[data-lang-btn]").forEach((button) => {
    button.classList.toggle("active", button.dataset.langBtn === currentLanguage);
  });

  inputEl.placeholder = t("demo.placeholder");

  document.querySelector('input[name="name"]').placeholder = t("form.name");
  document.querySelector('input[name="name"]').setAttribute("aria-label", t("form.name"));
  document.querySelector('input[name="email"]').placeholder = t("form.email");
  document.querySelector('input[name="email"]').setAttribute("aria-label", t("form.email"));
  document.querySelector('input[name="business"]').placeholder = t("form.business");
  document.querySelector('input[name="business"]').setAttribute("aria-label", t("form.business"));
  document.querySelector('input[name="workflow"]').placeholder = t("form.workflow");
  document.querySelector('input[name="workflow"]').setAttribute("aria-label", t("form.workflow"));

  updateUI();
}

function setLanguage(language) {
  if (currentLanguage === language) return;

  currentLanguage = language;
  localStorage.setItem("echoFourLanguage", language);
  data = {};
  messagesEl.replaceChildren();
  inputEl.value = "";
  applyLanguage();
  addMessage(t("demo.initialMessage"), "bot");
  inputEl.focus();
}

function resetFormTimer() {
  formStartedAtEl.value = String(Date.now());
}

function addMessage(text, type) {
  const div = document.createElement("div");
  div.className = "msg " + type;
  div.innerText = text;
  messagesEl.appendChild(div);
  messagesEl.scrollTop = messagesEl.scrollHeight;
  return div;
}

function setText(id, value) {
  document.getElementById(id).textContent = value;
}

function updateUI() {
  const isAutomation = data.mode !== "service";

  setText("issueLabel", isAutomation ? t("dashboard.opportunity") : t("dashboard.issue"));
  setText("urgencyLabel", isAutomation ? t("dashboard.stage") : t("dashboard.urgency"));
  setText("estimateLabel", isAutomation ? t("dashboard.scope") : t("dashboard.estimate"));
  setText("cityLabel", isAutomation ? t("dashboard.market") : t("dashboard.location"));
  setText("integrationLabel", isAutomation ? t("dashboard.integration") : t("dashboard.channel"));
  setText("nextStepLabel", isAutomation ? t("dashboard.nextStep") : t("dashboard.status"));

  setText("issueValue", translateValue(data.issue) || t("dashboard.waiting"));
  setText("urgencyValue", translateValue(data.urgency) || t("dashboard.pending"));
  setText("estimateValue", translateValue(data.estimate) || t("dashboard.pending"));
  setText("cityValue", translateValue(data.city) || t("dashboard.unknown"));
  setText("integrationValue", translateValue(data.integration) || (isAutomation ? t("dashboard.toConfirm") : t("dashboard.websiteChat")));
  setText("nextStepValue", translateValue(data.nextStep) || (isAutomation ? t("dashboard.qualifyProject") : t("dashboard.collectDetails")));
  setText("contactValue", data.contact || t("dashboard.notCaptured"));

  const confidence = data.confidence || 0;
  setText("confidenceBadge", confidence ? confidence + "% " + t("dashboard.match") : t("dashboard.analyzing"));
  document.getElementById("readyState").hidden = !data.contact;
}

function usePrompt(prompt) {
  inputEl.value = prompt;
  inputEl.focus();
}

function resetDemo() {
  data = {};
  messagesEl.replaceChildren();
  inputEl.value = "";
  addMessage(t("demo.initialMessage"), "bot");
  updateUI();
  inputEl.focus();
}

document.getElementById("contactForm").addEventListener("submit", async function(e) {
  e.preventDefault();

  const form = e.currentTarget;
  const status = document.getElementById("formStatus");
  const payload = Object.fromEntries(new FormData(form).entries());

  status.textContent = t("form.sending");

  try {
    const res = await fetch("/lead", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload)
    });

    if (!res.ok) throw new Error("Request failed");

    status.textContent = t("form.success");
    form.reset();
    resetFormTimer();
  } catch (error) {
    status.textContent = t("form.error");
  }
});

