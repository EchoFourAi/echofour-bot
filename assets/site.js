async function send() {
  const message = inputEl.value.trim();
  if (!message) return;

  addMessage(message, "user");
  inputEl.value = "";
  const typing = addMessage(t("demo.typing"), "bot typing");

  try {
    const res = await fetch("/chat", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ message, data, industry: "service", language: currentLanguage })
    });

    const json = await res.json();
    data = json.data || data;
    applyDemoSignals(message);
    typing.remove();
    addMessage(json.reply || t("demo.fallback"), "bot");
  } catch (error) {
    applyDemoSignals(message);
    typing.remove();
    addMessage(t("demo.fallback"), "bot");
  }

  updateUI();
}

inputEl.addEventListener("keydown", function(e) {
  if (e.key === "Enter" && !e.shiftKey) {
    e.preventDefault();
    send();
  }
});

